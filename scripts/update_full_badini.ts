// Helper to escape regex special characters
function escapeRegExp(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Deduplicate patterns by source string
const patternMap = new Map<string, string>();
for (const [from, to] of RAW_SORANI_TO_BADINI) {
  if (from.trim().length > 0) {
    patternMap.set(from, to);
  }
}

// Sort descending by pattern length so longer phrases match first
const sortedPatterns = Array.from(patternMap.entries()).sort((a, b) => b[0].length - a[0].length);

// Compile all patterns with Unicode letter boundaries
const COMPILED_PATTERNS: Array<[RegExp, string]> = sortedPatterns.map(([from, to]) => [
  new RegExp(`(?<![\\p{L}\\p{M}])${escapeRegExp(from)}(?![\\p{L}\\p{M}])`, 'gu'),
  to
]);

function transformText(str: string): string {
  let res = str;
  for (const [pat, rep] of COMPILED_PATTERNS) {
    res = res.replace(pat, rep);
  }
  // Contextual pass for 'لە' before words ending in 'دا' -> 'د $1'
  res = res.replace(/(?<![\p{L}\p{M}])لە\s+([\p{L}\p{M}\d_]+دا)(?![\p{L}\p{M}])/gu, 'د $1');
  return res;
}

function recursiveTransform(obj: any) {
  for (const key of Object.keys(obj)) {
    if (typeof obj[key] === 'string') {
      if (!obj[key].match(/^[\d\s.,\-+/()=*^%#@!?:;]+$/) && !obj[key].startsWith('http')) {
        obj[key] = transformText(obj[key]);
      }
    } else if (Array.isArray(obj[key])) {
      obj[key] = obj[key].map((item: any) => {
        if (typeof item === 'string') {
          return transformText(item);
        } else if (typeof item === 'object' && item !== null) {
          recursiveTransform(item);
          return item;
        }
        return item;
      });
    } else if (typeof obj[key] === 'object' && obj[key] !== null) {
      recursiveTransform(obj[key]);
    }
  }
}

// Transform all sections of bad
for (const sec of Object.keys(bad)) {
  if (typeof bad[sec] === 'object' && bad[sec] !== null) {
    recursiveTransform(bad[sec]);
  }
}

// Final sanity check: Key parity
function getKeyPaths(obj: any, prefix = ''): string[] {
  let paths: string[] = [];
  for (const [k, v] of Object.entries(obj)) {
    const full = prefix ? `${prefix}.${k}` : k;
    if (typeof v === 'object' && v !== null && !Array.isArray(v)) {
      paths.push(...getKeyPaths(v, full));
    } else {
      paths.push(full);
    }
  }
  return paths;
}

