def apply_terms(text):
    if not isinstance(text, str):
        return text
    # Preserve placeholders
    placeholders = []
    def repl_ph(match):
        placeholders.append(match.group(0))
        return f"__PH_{len(placeholders)-1}__"
    
    s = re.sub(r"\{\{[^}]+\}\}", repl_ph, text)
    for pat, rep in EXPERIMENT_REPLACEMENTS:
        s = re.sub(pat, rep, s)
    for idx, ph in enumerate(placeholders):
        s = s.replace(f"__PH_{idx}__", ph)
    return s

def translate_obj(node):
    if isinstance(node, dict):
        return {k: translate_obj(v) for k, v in node.items()}
    elif isinstance(node, list):
        return [translate_obj(item) for item in node]
    elif isinstance(node, str):
        return apply_terms(node)
    else:
        return node

